package hyprland

import (
	"bufio"
	"context"
	"errors"
	"fmt"
	"io"
	"log"
	"net"
	"os"
	"path/filepath"
	"time"

	"dfs-daemon/internal/events"
)

const defaultRetryInterval = 3 * time.Second
const maxEventLineBytes = 1024 * 1024

// Adapter reads events from the Hyprland-specific socket. Other compositor
// adapters can implement the same event publishing contract without changing
// the WebSocket transport or shell UI.
type Adapter struct {
	SocketPath    string
	RetryInterval time.Duration
	Logger        *log.Logger
}

func SocketPathFromEnv() (string, error) {
	signature := os.Getenv("HYPRLAND_INSTANCE_SIGNATURE")
	if signature == "" {
		return "", errors.New("HYPRLAND_INSTANCE_SIGNATURE is not set; start DFS inside a Hyprland session")
	}
	// The signature is generated by Hyprland but is still treated as input.
	if filepath.Base(signature) != signature || signature == "." || signature == ".." {
		return "", fmt.Errorf("invalid HYPRLAND_INSTANCE_SIGNATURE %q", signature)
	}

	if runtimeDir := os.Getenv("XDG_RUNTIME_DIR"); runtimeDir != "" {
		return filepath.Join(runtimeDir, "hypr", signature, ".socket2.sock"), nil
	}
	return filepath.Join("/tmp", "hypr", signature, ".socket2.sock"), nil
}

func (a *Adapter) Run(ctx context.Context, publish func(events.Event)) error {
	if a.SocketPath == "" {
		return errors.New("Hyprland socket path is empty")
	}
	if publish == nil {
		return errors.New("event publisher is nil")
	}
	logger := a.Logger
	if logger == nil {
		logger = log.Default()
	}
	retry := a.RetryInterval
	if retry <= 0 {
		retry = defaultRetryInterval
	}

	for {
		if err := ctx.Err(); err != nil {
			return nil
		}
		conn, err := net.DialTimeout("unix", a.SocketPath, 3*time.Second)
		if err != nil {
			logger.Printf("Hyprland IPC connect failed: %v; retrying in %s", err, retry)
			if !sleepContext(ctx, retry) {
				return nil
			}
			continue
		}

		logger.Printf("Connected to Hyprland IPC socket at %s", a.SocketPath)
		err = a.consume(ctx, conn, publish)
		_ = conn.Close()
		if ctx.Err() != nil {
			return nil
		}
		if err != nil && !errors.Is(err, io.EOF) {
			logger.Printf("Hyprland IPC stream ended: %v", err)
		} else {
			logger.Printf("Hyprland IPC connection closed; retrying in %s", retry)
		}
		if !sleepContext(ctx, retry) {
			return nil
		}
	}
}

func (a *Adapter) consume(ctx context.Context, conn net.Conn, publish func(events.Event)) error {
	readDone := make(chan struct{})
	defer close(readDone)
	go func() {
		select {
		case <-ctx.Done():
			_ = conn.Close()
		case <-readDone:
		}
	}()

	scanner := bufio.NewScanner(conn)
	scanner.Buffer(make([]byte, 64*1024), maxEventLineBytes)
	for scanner.Scan() {
		if err := ctx.Err(); err != nil {
			return nil
		}
		if event, ok := events.ParseHyprland(scanner.Text()); ok {
			publish(event)
		}
	}
	return scanner.Err()
}

func sleepContext(ctx context.Context, duration time.Duration) bool {
	timer := time.NewTimer(duration)
	defer timer.Stop()
	select {
	case <-ctx.Done():
		return false
	case <-timer.C:
		return true
	}
}
